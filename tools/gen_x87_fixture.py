#!/usr/bin/env python3
"""Generates src/x87_fixture_test.odin: expected trunc(a / (100/scale)) as
computed by the x87 FPU (64-bit mantissa, round-to-nearest), using exact
fractions. Independent oracle for x87_scale_trunc."""
import math
from fractions import Fraction as F


def x87(v):
    if v == 0:
        return v
    e = math.floor(math.log2(abs(v)))
    return F(round(v / F(2) ** (e - 63))) * F(2) ** (e - 63)


AS = list(range(1, 11)) + [60, 72, 96, 200, 320]
rows = []
for a in AS:
    vals = [int(x87(F(a) / x87(F(100) / s))) for s in range(1, 101)]
    rows.append(f"\t{{{a}, {{{', '.join(map(str, vals))}}}}},")
with open("src/x87_fixture_test.odin", "w") as f:
    f.write("#+build !js\npackage vc\n\n// Generated by tools/gen_x87_fixture.py. Do not edit.\n\n")
    f.write("X87_FIXTURE := [?]struct {\n\ta:   int,\n\tout: [100]int, // scale 1..100\n}{\n")
    f.write("\n".join(rows) + "\n}\n")
