// Renders the original's three GDI fonts as 1-bit, fully hinted bitmaps
// (as Windows drew unsmoothed TrueType text) and writes them as a JS table
// for web/gdifont.js.
//
//   clang -O2 -I/opt/homebrew/include/freetype2 tools/gdifont.c \
//     -L/opt/homebrew/lib -lfreetype -o /tmp/gdifont && /tmp/gdifont > web/gdifont.js
//
// Fonts (0x41b590): CreateFontA(height, ..., weight, italic, ..., "Arial")
// with a positive height, i.e. the cell height (ascent + descent).
#include <ft2build.h>
#include FT_FREETYPE_H
#include FT_MODULE_H
#include FT_TRUETYPE_TABLES_H
#include <stdio.h>
#include <math.h>

typedef struct {
	const char *key;  // font string the page uses
	const char *file; // macOS copy of the same Arial
	int cell;         // GDI cell height
} Font;

static const Font FONTS[] = {
	{"11px Arial, sans-serif", "/System/Library/Fonts/Supplemental/Arial.ttf", 12},             // tooltips (0x4526b8)
	{"bold 16px Arial, sans-serif", "/System/Library/Fonts/Supplemental/Arial Bold.ttf", 18},   // Options box (0x451744)
	{"italic bold 14px Arial, sans-serif", "/System/Library/Fonts/Supplemental/Arial Bold Italic.ttf", 16}, // (0x44f798)
};

int main(void) {
	FT_Library lib;
	if (FT_Init_FreeType(&lib)) return 1;
	// the classic (Windows-like) TrueType interpreter: full hinting in x and y
	FT_UInt v35 = 35;
	FT_Property_Set(lib, "truetype", "interpreter-version", &v35);
	printf("// Generated by tools/gdifont.c from Arial (macOS copy), rendered 1-bit with\n");
	printf("// full TrueType hinting, as GDI drew the original's unsmoothed text.\n");
	printf("// Per font: cell height and glyphs: [advance, first row, x offset, rows...].\n");
	printf("\"use strict\";\nconst GDI_FONTS = {\n");
	for (unsigned f = 0; f < sizeof FONTS / sizeof FONTS[0]; f++) {
		FT_Face face;
		if (FT_New_Face(lib, FONTS[f].file, 0, &face)) { fprintf(stderr, "no %s\n", FONTS[f].file); return 1; }
		TT_OS2 *os2 = FT_Get_Sfnt_Table(face, FT_SFNT_OS2);
		double units = os2 ? os2->usWinAscent + os2->usWinDescent : face->ascender - face->descender;
		// GDI maps the cell height onto winAscent + winDescent
		double ppem = FONTS[f].cell * face->units_per_EM / units;
		// (hinted at a whole number of pixels per em)
		FT_Set_Pixel_Sizes(face, 0, (FT_UInt)lround(ppem));
		int ascent = (int)lround((os2 ? os2->usWinAscent : face->ascender) * ppem / face->units_per_EM);
		printf("\t\"%s\": { cell: %d, ppem: %.2f, glyphs: {\n", FONTS[f].key, FONTS[f].cell, ppem);
		for (int ch = 32; ch < 127; ch++) {
			if (FT_Load_Char(face, ch, FT_LOAD_RENDER | FT_LOAD_TARGET_MONO | FT_LOAD_MONOCHROME)) continue;
			FT_GlyphSlot g = face->glyph;
			int adv = (int)((g->advance.x + 32) >> 6);
			FT_Bitmap *b = &g->bitmap;
			printf("\t\t");
			if (ch == '"' || ch == '\\') printf("\"\\%c\"", ch); else printf("\"%c\"", ch);
			printf(": [%d, %d, %d", adv, ascent - g->bitmap_top, g->bitmap_left);
			for (unsigned y = 0; y < b->rows; y++) {
				printf(", \"");
				for (unsigned x = 0; x < b->width; x++) {
					unsigned char byte = b->buffer[y * b->pitch + x / 8];
					putchar(byte & (0x80 >> (x % 8)) ? '#' : '.');
				}
				putchar('"');
			}
			printf("],\n");
		}
		printf("\t} },\n");
		FT_Done_Face(face);
	}
	printf("};\n");
	FT_Done_FreeType(lib);
	return 0;
}
